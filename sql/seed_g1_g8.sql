-- ============================================================
-- ПРОВЕРКА 1: qh_rows
--
-- Ожидается:
-- Г.1 = 29
-- Г.2 = 29
-- Г.3 = 24
-- Г.4 = 24
-- Г.5 = 26
-- Г.6 = 26
-- Г.7 = 31
-- Г.8 = 10
-- ИТОГО = 199
-- ============================================================

SELECT
    t.code,
    count(*) AS rows_count
FROM qh_rows r
JOIN qh_tables t
    ON t.id = r.table_id
WHERE t.code IN ('Г.1','Г.2','Г.3','Г.4','Г.5','Г.6','Г.7','Г.8')
  AND r.is_active = true
GROUP BY t.code
ORDER BY t.code;


-- ============================================================
-- ПРОВЕРКА 2: qh_values
--
-- Ожидается:
-- Г.1 = 348
-- Г.2 = 348
-- Г.3 = 400
-- Г.4 = 409
-- Г.5 = 234
-- Г.6 = 234
-- Г.7 = 124
-- Г.8 = 20
-- ИТОГО = 2117
-- ============================================================

SELECT
    t.code,
    count(*) AS values_count
FROM qh_values v
JOIN qh_rows r
    ON r.id = v.row_id
JOIN qh_tables t
    ON t.id = r.table_id
WHERE t.code IN ('Г.1','Г.2','Г.3','Г.4','Г.5','Г.6','Г.7','Г.8')
GROUP BY t.code
ORDER BY t.code;


-- ============================================================
-- ПРОВЕРКА 3: placement / density / role
-- ============================================================

SELECT
    t.code,
    v.pipeline_role,
    COALESCE(v.placement_variant, '<NULL>') AS placement_variant,
    v.density_kind,
    count(*) AS values_count
FROM qh_values v
JOIN qh_rows r
    ON r.id = v.row_id
JOIN qh_tables t
    ON t.id = r.table_id
WHERE t.code IN ('Г.1','Г.2','Г.3','Г.4','Г.5','Г.6','Г.7','Г.8')
GROUP BY
    t.code,
    v.pipeline_role,
    v.placement_variant,
    v.density_kind
ORDER BY
    t.code,
    v.pipeline_role,
    placement_variant,
    v.density_kind;
