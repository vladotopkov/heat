-- ============================================================

INSERT INTO qh_rows (
    table_id,
    source_row_no,
    note,
    is_active
)
SELECT
    t.id,
    s.source_row_no,
    s.note,
    true
FROM tmp_g_rows_seed s
JOIN qh_tables t
    ON t.code = s.table_code
ON CONFLICT (table_id, source_row_no)
DO UPDATE SET
    note = EXCLUDED.note,
    is_active = true;


-- Старые лишние строки, если когда-то были загружены,
-- выключаем, а не оставляем участвовать в выборе.
UPDATE qh_rows r
SET is_active = false
FROM qh_tables t
WHERE t.id = r.table_id
  AND t.code IN ('Г.1','Г.2','Г.3','Г.4','Г.5','Г.6','Г.7','Г.8')
  AND NOT EXISTS (
      SELECT 1
      FROM tmp_g_rows_seed s
      WHERE s.table_code = t.code
        AND s.source_row_no = r.source_row_no
  );


